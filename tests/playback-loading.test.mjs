import assert from "node:assert/strict";
import { waitForPlaybackEvent } from "../services/playback-loading.js";
import { createOffscreenHarness } from "./helpers/offscreen.mjs";
const { audio, pending, run, flush } = await createOffscreenHarness();
const first = run('handleCommand("playQueue", {queue:[{id:"A"},{id:"B"}]})');
await flush();
const second = run('handleCommand("playIndex", {index:1})');
await flush();
pending.get('B')({ ok: true, data: { url: 'https://cdn/B' } });
await second;
pending.get('A')({ ok: true, data: { url: 'https://cdn/A' } });
await first;
assert.equal(run('state.currentTrack.id'), 'B');
assert.equal(audio.loads.length, 1);
assert.equal(audio.paused, false);
const pausedLoad = run('handleCommand("playIndex", {index:0})');
await flush();
await run('handleCommand("pause")');
pending.get('A')({ ok: true, data: { url: 'https://cdn/A' } });
await pausedLoad;
assert.equal(audio.paused, true, 'loading must respect the latest pause');
const clearedLoad = run('handleCommand("playIndex", {index:1})');
await flush();
await run('handleCommand("clearQueue")');
pending.get('B')({ ok: true, data: { url: 'https://cdn/B' } });
await clearedLoad;
assert.equal(audio.src, '');
assert.equal(run('state.currentTrack'), null);
const controller = new AbortController();
const target = new EventTarget();
const waiting = waitForPlaybackEvent(target, 'canplay', controller.signal, () => new Error('bad'));
controller.abort();
await assert.rejects(waiting, { name: 'AbortError' });
await assert.rejects(run('waitForBufferSpace({buffered:{length:0}}, (()=>{const c=new AbortController();c.abort();return c.signal;})())'), { name: 'AbortError' });
assert.throws(() => run('appendToSourceBuffer({}, new Uint8Array(), (()=>{const c=new AbortController();c.abort();return c.signal;})())'), { name: 'AbortError' });
const seeking = await createOffscreenHarness({ waitForPlaybackEvent: async () => { throw new Error("定位等待超时"); } });
seeking.audio.seeking = true;
await assert.rejects(seeking.run('activeLoad={controller:new AbortController()}; seekToResumePosition("缓存",50,activeLoad,activeLoad.controller.signal)'), { code: "RESUME_SEEK_FAILED" });
console.log('播放加载竞态：反序切歌、加载中暂停、清空和媒体等待取消通过');
